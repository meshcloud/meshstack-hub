#!/usr/bin/env node
/**
 * Renders every `*.dot` diagram in the repo to a sibling `*.svg`.
 *
 *   node tools/diagrams/render-diagrams.mjs            # write the SVGs
 *   node tools/diagrams/render-diagrams.mjs --check    # fail if any SVG is stale
 *
 * Graphviz runs as a WASM module from node_modules, so no system `dot` install
 * is required. The `--check` mode is what CI runs: it re-renders in memory and
 * compares against what is committed, so a `.dot` edit without a re-render fails
 * the build instead of silently shipping a stale picture.
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { Graphviz } from "@hpcc-js/wasm-graphviz";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const SKIP_DIRS = new Set([
  ".git",
  ".terraform",
  "node_modules",
  "dist",
  ".go",
]);

function findDotFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) return [];
      return findDotFiles(join(dir, entry.name));
    }
    return entry.isFile() && entry.name.endsWith(".dot")
      ? [join(dir, entry.name)]
      : [];
  });
}

/**
 * Drops the generator comment so the committed SVG does not churn on every
 * Graphviz version bump, and keeps a trailing newline for well-behaved diffs.
 */
function normalize(svg) {
  return svg
    .replace(/<!--\s*Generated by graphviz[\s\S]*?-->\s*/g, "")
    .replace(/<!--\s*Title:[\s\S]*?-->\s*/g, "")
    .replace(/\s*$/, "\n");
}

const check = process.argv.includes("--check");
const graphviz = await Graphviz.load();
const dotFiles = findDotFiles(repoRoot).sort();

if (dotFiles.length === 0) {
  console.log("No .dot diagrams found.");
  process.exit(0);
}

const stale = [];

for (const dotPath of dotFiles) {
  const svgPath = join(dirname(dotPath), `${basename(dotPath, ".dot")}.svg`);
  const rel = relative(repoRoot, svgPath);

  let rendered;
  try {
    rendered = normalize(graphviz.layout(readFileSync(dotPath, "utf8"), "svg", "dot"));
  } catch (err) {
    console.error(`❌ ${relative(repoRoot, dotPath)}: ${err.message}`);
    process.exit(1);
  }

  const current = existsAsFile(svgPath) ? readFileSync(svgPath, "utf8") : null;

  if (current === rendered) {
    console.log(`✅ ${rel} up to date`);
    continue;
  }

  if (check) {
    stale.push(rel);
    console.error(`❌ ${rel} is ${current === null ? "missing" : "stale"}`);
    continue;
  }

  writeFileSync(svgPath, rendered);
  console.log(`✏️  ${rel} ${current === null ? "created" : "updated"}`);
}

function existsAsFile(p) {
  try {
    return statSync(p).isFile();
  } catch {
    return false;
  }
}

if (stale.length > 0) {
  console.error(
    `\n${stale.length} diagram(s) out of date. Run \`task diagrams\` and commit the result.`
  );
  process.exit(1);
}
